"""失败测甲：发布完成后，装载与校验必须认同一发布版本。

红条件：发布后再灌越新阈点仍按旧阈进现行（页绿实旧）。
"""
from app.services import 装载, 目录, 校验, 阈版本, 夹具


def _越阈报文(编号: str, 读数: float) -> dict:
    return {
        "批次编号": "测甲",
        "报文": [{
            "报文编号": 编号,
            "站点键": "站-河东",
            "指标键": "PM25",
            "读数": 读数,
            "观测时": "2026-11-25T08:00:00Z",
        }],
    }


def test_草稿不进现行_装载仍认种子阈():
    # 种子现行阈：PM25上限=75。草稿改成 50 但不发布，装载必须仍按 75 分流。
    目录.改栏规({"PM25上限": "50"})
    报告 = 装载.装一批(_越阈报文("A-draft-1", 60.0))
    assert 报告["入栏"] == 1, "草稿阈不得影响现行装载"
    assert 阈版本.现行凭证()["版本号"] == "v0"
    assert 阈版本.现行栏规()["PM25上限"] == "75"


def test_发布后越新阈点按新阈进坏点匣():
    目录.改栏规({"PM25上限": "50"})
    发布 = 阈版本.发布草稿()
    assert 发布["版本号"] == "v1"

    凭证 = 阈版本.现行凭证()
    assert 凭证["版本号"] == "v1"
    assert 凭证["指纹"] == 发布["指纹"]
    assert 凭证["拒旧阈回刷"] is 1

    # 60 在旧阈 [0,75] 下应入栏，在新阈 [0,50] 下必须进坏点匣。
    报告 = 装载.装一批(_越阈报文("A-pub-1", 60.0))
    assert 报告["坏点"] == 1, "发布后装载仍吃旧阈 → 页绿实旧"
    assert 报告["入栏"] == 0
    assert 报告["发布版本"] == "v1"
    assert 报告["阈指纹"] == 发布["指纹"]
    坏点 = 目录.坏点列表()
    assert 坏点 and 坏点[0]["报文编号"] == "A-pub-1"
    # 校验与装载同读一条发布版本，不允许各读各的。
    ok, _ = 校验.过门槛(60.0, 阈版本.现行栏规(), "PM25")
    assert ok is False
    ok2, _ = 校验.过门槛(40.0, 阈版本.现行栏规(), "PM25")
    assert ok2 is True


def test_旧阈指纹回刷被拒():
    目录.改栏规({"PM25上限": "50"})
    发布 = 阈版本.发布草稿()
    旧指纹 = 阈版本.现行凭证()["指纹"]

    目录.改栏规({"PM25上限": "40"})
    阈版本.发布草稿()
    assert 阈版本.现行凭证()["版本号"] == "v2"

    # 拿 v1 的旧指纹试图把现行读轨刷回旧阈，必须被拒并留痕。
    果 = 阈版本.拒旧阈回刷(旧指纹)
    assert 果["拒绝"] is True
    记录 = 阈版本.回刷记录()
    assert any(r["旧指纹"] == 旧指纹 for r in 记录)
    # 现行仍是 v2，不被旧指纹带回 v1。
    assert 阈版本.现行凭证()["版本号"] == "v2"
    assert 阈版本.现行栏规()["PM25上限"] == "40"


def test_重复发布同稿幂等不裂版本():
    目录.改栏规({"PM25上限": "50"})
    第一次 = 阈版本.发布草稿()
    第二次 = 阈版本.发布草稿()
    assert 第一次["版本号"] == 第二次["版本号"]
    assert 第一次["指纹"] == 第二次["指纹"]
    历史 = 阈版本.版本历史()
    assert len(历史) == 2  # v0 种子 + v1
    凭证 = 阈版本.现行凭证()
    # 凭证指纹必须能在已发布阈集里找到同指纹版本，杜绝悬空凭证。
    assert 阈版本.指纹对版(凭证["指纹"])["版本号"] == "v1"


def test_发布后结栏按页阈不再对空账():
    目录.改栏规({"PM25上限": "50"})
    阈版本.发布草稿()
    装载.装一批(_越阈报文("A-close-1", 60.0))
    from app.services import 结栏
    预览 = 结栏.预览结栏()
    assert 预览["在栏"] == 0, "新阈坏点不得占栏，结栏不得再按页阈对空账"
    报告 = 结栏.结当前栏()
    assert 报告["空栏"] is True
